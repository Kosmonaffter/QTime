class HelpDialog(tk.Toplevel):
    """Модальное окно с пошаговой инструкцией."""

    def __init__(self, parent):
        super().__init__(parent)
        self.title(HELP_TITLE)
        self.geometry("700x640")
        self.transient(parent)
        self.grab_set()

        self._build_ui()

    def _build_ui(self):
        """Собирает прокручиваемое содержимое инструкции."""
        container = ttk.Frame(self, padding=12)
        container.pack(fill="both", expand=True)

        canvas = tk.Canvas(container, borderwidth=0, highlightthickness=0)
        scrollbar = ttk.Scrollbar(
            container, orient="vertical", command=canvas.yview
        )
        inner = ttk.Frame(canvas)

        inner.bind(
            "<Configure>",
            lambda event: canvas.configure(
                scrollregion=canvas.bbox("all")
            ),
        )
        canvas.create_window((0, 0), window=inner, anchor="nw")
        canvas.configure(yscrollcommand=scrollbar.set)

        canvas.pack(side="left", fill="both", expand=True)
        scrollbar.pack(side="right", fill="y")

        self._bind_mousewheel(canvas)

        for title, body in HELP_SECTIONS:
            ttk.Label(
                inner,
                text=title,
                font=("Segoe UI", 11, "bold"),
            ).pack(anchor="w", pady=(10, 4))
            ttk.Label(
                inner,
                text=body,
                wraplength=620,
                justify="left",
            ).pack(anchor="w")

        ttk.Separator(inner, orient="horizontal").pack(
            fill="x", pady=12
        )
        ttk.Label(
            inner,
            text=CONTACT_LINE,
            justify="left",
            foreground="#555555",
        ).pack(anchor="w")

        ttk.Button(
            inner,
            text="Понятно",
            command=self.destroy,
        ).pack(anchor="e", pady=12)

    def _bind_mousewheel(self, canvas):
        """Привязывает колесо мыши к прокрутке Canvas."""
        def _on_wheel(event):
            if event.num == 4:
                delta = -1
            elif event.num == 5:
                delta = 1
            else:
                delta = -1 if event.delta > 0 else 1
            canvas.yview_scroll(delta, "units")

        canvas.bind_all("<MouseWheel>", _on_wheel)
        canvas.bind_all("<Button-4>", _on_wheel)
        canvas.bind_all("<Button-5>", _on_wheel)

    def destroy(self):
        """Отвязывает колесо мыши перед закрытием окна."""
        self.unbind_all("<MouseWheel>")
        self.unbind_all("<Button-4>")
        self.unbind_all("<Button-5>")
        super().destroy()
